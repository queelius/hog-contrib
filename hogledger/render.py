"""Generate per-record pages, the README deposit table, CITATION.cff and .zenodo.json.

Every generated fact comes from contributions.yaml, the witness files or the
receipts. write() rewrites the outputs; stale() lists those that differ.
"""

from collections import Counter
import hashlib
from itertools import groupby
import json
from pathlib import Path

import yaml

from . import registry
from .model import ClaimKind, Ledger, Record, Status

PAGES = Path("docs/graphs")
BEGIN = "<!-- BEGIN GENERATED: deposits -->"
END = "<!-- END GENERATED: deposits -->"
GENERATED = "Generated by hogledger render from contributions.yaml. Do not edit."
NOTICE = f"<!-- {GENERATED} -->"
MARKDOWN_SPECIAL = "\\`*_[]<>|"


def markdown_text(text: str) -> str:
    """Escape text so that Markdown renders it literally."""
    return "".join("\\" + c if c in MARKDOWN_SPECIAL else c for c in text)


def fence(text: str) -> str:
    """A code fence longer than any backtick run in text."""
    longest = max((len(list(run)) for char, run in groupby(text) if char == "`"), default=0)
    return "`" * max(3, longest + 1)


def link(source: str) -> str:
    """A Markdown link for a doi:... or URL source."""
    url = "https://doi.org/" + source.removeprefix("doi:") if source.startswith("doi:") else source
    return f"[{markdown_text(source)}]({url})"


def kind_label(kind: ClaimKind) -> str:
    return kind.value.replace("_", " ")


def hog_url(ledger: Ledger, record: Record) -> str:
    return f"{ledger.house_of_graphs}/graphs/{record.hog_id}"


def citation(ledger: Ledger, record: Record) -> str:
    author = ledger.author
    where = f"doi:{ledger.doi}" if ledger.doi else ledger.repository
    lines = [f"{author.family_names}, {author.given_names}. {ledger.title}, "
             f"version {ledger.version}, record {record.case.id}. {where}"]
    if record.hog_id is not None:
        lines.append(f"Witness: House of Graphs graph {record.hog_id}, {hog_url(ledger, record)}")
    if record.zenodo:
        lines.append(f"Evidence: doi:{record.zenodo}")
    return "\n".join(lines)


def page(ledger: Ledger, record: Record, root: Path) -> str:
    case, claim = record.case, record.case.claim
    witness = (root / case.path).read_bytes()
    graph6_fence = fence(case.graph6)
    hog = (f"[House of Graphs {record.hog_id}]({hog_url(ledger, record)})"
           if record.hog_id is not None else "not on House of Graphs")
    rows = [
        ("Status", f"{record.status.value}, {hog}"),
        ("Order and size", f"{case.n} vertices, {case.edges} edges"),
        ("Witness file", f"[{case.path}](../../{case.path})"),
        ("Witness SHA-256", f"`{hashlib.sha256(witness).hexdigest()}`"),
        ("Certificates", markdown_text(record.certificates)),
    ]
    if record.non_iso_minima is not None:
        rows.append(("Minimum classes", str(record.non_iso_minima)))
    if record.zenodo:
        rows.append(("Archived evidence", link("doi:" + record.zenodo)))
    lines = [
        NOTICE, "", f"# {markdown_text(record.invariant)}", "",
        f"Record `{case.id}`: **{kind_label(claim.kind)}**.", "",
        f"> {markdown_text(claim.statement)}", "",
        "| | |", "| --- | --- |", *(f"| {key} | {value} |" for key, value in rows), "",
        "graph6:", "", graph6_fence + "text", case.graph6, graph6_fence, "",
        "## Prior art", "",
    ]
    if claim.prior_art:
        for entry in claim.prior_art:
            where = f" ({markdown_text(entry.locator)})" if entry.locator else ""
            lines.append(f"- {link(entry.source)}{where}, checked {entry.checked.isoformat()}: "
                         f"{markdown_text(entry.finding)}")
    else:
        lines.append("None recorded.")
    if claim.kind is ClaimKind.UNASSESSED:
        lines += ["", "The prior-art status of this record has not been assessed. "
                  "It makes no novelty claim."]
    lines += [
        "", "## Verify", "",
        "From the repository root, with the dependencies in `pyproject.toml` installed "
        "(`python3 -m pip install .`):", "",
        "```", f"python3 -m hogledger verify {case.id}", "```", "",
        "Two separate implementations must both accept the witness.", "",
        "## Cite", "", "```text", citation(ledger, record), "```", "",
    ]
    receipts = [r for r in ledger.receipts if case.id in r.records]
    if receipts:
        lines += ["## Receipts", ""]
        lines += [f"- [{r.path.stem}](../../{r.path})"
                  + (f": {markdown_text(r.summary)}" if r.summary else "") for r in receipts]
        lines.append("")
    if record.notes:
        lines += ["## History", "", markdown_text(record.notes), ""]
    return "\n".join(lines)


def deposits_table(ledger: Ledger) -> str:
    statuses = Counter(record.status for record in ledger.records)
    kinds = Counter(record.case.claim.kind for record in ledger.records)
    summary = (f"{len(ledger.records)} records: "
               + ", ".join(f"{statuses[s]} {s.value}" for s in Status if statuses[s])
               + ". Claims: "
               + ", ".join(f"{kinds[k]} {kind_label(k)}" for k in ClaimKind if kinds[k]) + ".")
    rows = ["| Record | Invariant | n | Edges | Claim | House of Graphs | Status |",
            "| --- | --- | --- | --- | --- | --- | --- |"]
    for record in ledger.records:
        case = record.case
        hog = (f"[{record.hog_id}]({hog_url(ledger, record)})"
               if record.hog_id is not None else "")
        rows.append(f"| [{case.id}]({PAGES / case.id}.md) | {markdown_text(record.invariant)} "
                    f"| {case.n} | {case.edges} | {kind_label(case.claim.kind)} | {hog} "
                    f"| {record.status.value} |")
    return "\n".join([BEGIN, summary, "", *rows, END])


def readme(ledger: Ledger, current: str) -> str:
    before, begin, rest = current.partition(BEGIN)
    _, end, after = rest.partition(END)
    if not begin or not end:
        raise ValueError(f"README.md must contain the {BEGIN} and {END} markers")
    return before + deposits_table(ledger) + after


def citation_cff(ledger: Ledger) -> str:
    author = ledger.author
    data = {
        "cff-version": "1.2.0",
        "title": ledger.title,
        "message": "Cite the House of Graphs entry and the archived evidence for each "
                   "record; cite this ledger for the verified collection.",
        "type": "dataset",
        "version": ledger.version,
        **({"doi": ledger.doi} if ledger.doi else {}),
        "license": [ledger.data_license, ledger.code_license],
        "authors": [{"given-names": author.given_names, "family-names": author.family_names,
                     "alias": author.handle, "email": author.email,
                     "orcid": f"https://orcid.org/{author.orcid}"}],
        "abstract": ledger.abstract,
        "keywords": list(ledger.keywords),
        "repository-code": ledger.repository,
        "references": [{"type": "generic", "title": paper.title, "doi": paper.doi,
                        "authors": [{"given-names": author.given_names,
                                     "family-names": author.family_names}]}
                       for paper in ledger.papers],
    }
    return f"# {GENERATED}\n" + yaml.safe_dump(data, sort_keys=False, allow_unicode=True)


def zenodo_json(ledger: Ledger) -> str:
    """Zenodo deposit metadata for a release of the ledger."""
    author = ledger.author
    data = {
        "upload_type": "dataset",
        "title": ledger.title,
        "version": ledger.version,
        "description": ledger.abstract,
        "creators": [{"name": f"{author.family_names}, {author.given_names}", "orcid": author.orcid}],
        "keywords": list(ledger.keywords),
        "license": ledger.data_license.lower(),
        "related_identifiers": [{"identifier": paper.doi, "relation": "references",
                                 "scheme": "doi", "resource_type": "publication"}
                                for paper in ledger.papers],
    }
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


def outputs(root: Path) -> dict[Path, str]:
    """Every generated file, keyed by its path relative to root."""
    root = Path(root)
    ledger = registry.load_ledger(root)
    files = {PAGES / f"{record.case.id}.md": page(ledger, record, root) for record in ledger.records}
    files[Path("README.md")] = readme(ledger, (root / "README.md").read_text())
    files[Path("CITATION.cff")] = citation_cff(ledger)
    files[Path(".zenodo.json")] = zenodo_json(ledger)
    return files


def _orphans(root: Path, files: dict[Path, str]) -> list[Path]:
    return [path.relative_to(root) for path in sorted((root / PAGES).glob("*.md"))
            if path.relative_to(root) not in files]


def stale(root: Path) -> list[Path]:
    """Generated files that are missing, differ from a fresh render, or are orphaned."""
    root = Path(root)
    files = outputs(root)
    changed = [path for path, text in files.items()
               if not (root / path).is_file() or (root / path).read_text() != text]
    return sorted(changed + _orphans(root, files))


def write(root: Path) -> None:
    root = Path(root)
    files = outputs(root)
    for path in _orphans(root, files):
        (root / path).unlink()
    for path, text in files.items():
        (root / path).parent.mkdir(parents=True, exist_ok=True)
        (root / path).write_text(text)

